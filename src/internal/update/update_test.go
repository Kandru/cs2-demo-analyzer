func TestParseVersion(t *testing.T) {
	tests := []struct {
		in      string
		want    Version
		wantErr bool
	}{
		{in: "26.11.1", want: Version{26, 11, 1}},
		{in: "v26.11.2", want: Version{26, 11, 2}},
		{in: " 26.12.10 ", want: Version{26, 12, 10}},
		{in: "dev", wantErr: true},
		{in: "26.11", wantErr: true},
		{in: "26.11.x", wantErr: true},
		{in: "26.11.-1", wantErr: true},
		{in: "", wantErr: true},
	}
	for _, tt := range tests {
		got, err := ParseVersion(tt.in)
		if tt.wantErr {
			if err == nil {
				t.Errorf("ParseVersion(%q) = %v, want error", tt.in, got)
			}
			continue
		}
		if err != nil {
			t.Errorf("ParseVersion(%q): %v", tt.in, err)
			continue
		}
		if got != tt.want {
			t.Errorf("ParseVersion(%q) = %v, want %v", tt.in, got, tt.want)
		}
	}
}

func TestCompare(t *testing.T) {
	a := Version{26, 11, 2}
	b := Version{26, 11, 10}
	if Compare(a, b) != -1 {
		t.Fatal("build numbers should compare numerically")
	}
	if Compare(b, a) != 1 {
		t.Fatal("reverse comparison failed")
	}
	if Compare(a, a) != 0 {
		t.Fatal("equal versions should compare equal")
	}
	if Compare(Version{26, 12, 1}, Version{26, 11, 99}) != 1 {
		t.Fatal("month should outrank build number")
	}
	if Compare(Version{27, 1, 1}, Version{26, 12, 99}) != 1 {
		t.Fatal("year should outrank month")
	}
}

func TestParseChecksums(t *testing.T) {
	data := []byte(`# generated by sha256sum
0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef  cs2-demo-analyzer-26.11.2-linux-amd64.tar.gz
ABCDEF0123456789ABCDEF0123456789ABCDEF0123456789ABCDEF0123456789 *other.tar.gz
`)
	sums, err := ParseChecksums(data)
	if err != nil {
		t.Fatal(err)
	}
	if got := sums["cs2-demo-analyzer-26.11.2-linux-amd64.tar.gz"]; got != "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef" {
		t.Fatalf("archive hash = %q", got)
	}
	if got := sums["other.tar.gz"]; got != "abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789" {
		t.Fatalf("starred hash = %q", got)
	}
	if _, err := ParseChecksums([]byte("not a checksum")); err == nil {
		t.Fatal("expected malformed checksum to fail")
	}
	if _, err := ParseChecksums(nil); err == nil {
		t.Fatal("expected empty checksum file to fail")
	}
}

