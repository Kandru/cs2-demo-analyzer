func TestCheckAndApply(t *testing.T) {
	content := []byte("new binary contents")
	archive := makeArchive(t, "cs2-demo-analyzer-26.11.2-linux-amd64/cs2-demo-analyzer", content)
	sum := sha256.Sum256(archive)
	assetName := "cs2-demo-analyzer-26.11.2-linux-amd64.tar.gz"
	sums := fmt.Sprintf("%s  %s\n", hex.EncodeToString(sum[:]), assetName)

	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/repos/" + Repository + "/releases/latest":
			writeRelease(t, w, "v26.11.2", []releaseAsset{
				{Name: assetName, URL: "http://" + r.Host + "/download/archive"},
				{Name: checksumsAsset, URL: "http://" + r.Host + "/download/sums"},
			})
		case "/download/sums":
			_, _ = io.WriteString(w, sums)
		case "/download/archive":
			_, _ = w.Write(archive)
		default:
			http.NotFound(w, r)
		}
	}))
	defer server.Close()

	client := &Client{HTTP: server.Client(), APIBase: server.URL, GOOS: "linux", GOARCH: "amd64", Binary: BinaryName}
	st, err := client.Check(context.Background(), "26.11.1")
	if err != nil {
		t.Fatal(err)
	}
	if !st.Newer || st.Latest != "26.11.2" {
		t.Fatalf("status = %+v", st)
	}
	if st.Asset.Name != assetName || st.Checksums.Name != checksumsAsset {
		t.Fatalf("assets = %+v %+v", st.Asset, st.Checksums)
	}

	dir := t.TempDir()
	target := filepath.Join(dir, BinaryName)
	if err := os.WriteFile(target, []byte("old"), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := client.Apply(context.Background(), st, target); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(target)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, content) {
		t.Fatalf("target = %q", got)
	}
	info, err := os.Stat(target)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode().Perm() != 0o750 {
		t.Fatalf("mode = %v, want 0750", info.Mode().Perm())
	}
}

func TestApplyThroughSymlink(t *testing.T) {
	content := []byte("real binary")
	archive := makeArchive(t, "cs2-demo-analyzer-26.11.2-linux-amd64/cs2-demo-analyzer", content)
	sum := sha256.Sum256(archive)
	assetName := "cs2-demo-analyzer-26.11.2-linux-amd64.tar.gz"
	sums := fmt.Sprintf("%s  %s\n", hex.EncodeToString(sum[:]), assetName)

	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/repos/" + Repository + "/releases/latest":
			writeRelease(t, w, "26.11.2", []releaseAsset{
				{Name: assetName, URL: "http://" + r.Host + "/archive"},
				{Name: checksumsAsset, URL: "http://" + r.Host + "/sums"},
			})
		case "/sums":
			io.WriteString(w, sums)
		case "/archive":
			w.Write(archive)
		default:
			http.NotFound(w, r)
		}
	}))
	defer server.Close()

	dir := t.TempDir()
	target := filepath.Join(dir, BinaryName)
	if err := os.WriteFile(target, []byte("old"), 0o755); err != nil {
		t.Fatal(err)
	}
	link := filepath.Join(t.TempDir(), BinaryName)
	if err := os.Symlink(target, link); err != nil {
		t.Fatal(err)
	}

	client := &Client{HTTP: server.Client(), APIBase: server.URL, GOOS: "linux", GOARCH: "amd64", Binary: BinaryName}
	st, err := client.Check(context.Background(), "26.11.1")
	if err != nil {
		t.Fatal(err)
	}
	if err := client.Apply(context.Background(), st, link); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(target)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, content) {
		t.Fatalf("real target was not replaced: %q", got)
	}
	if fi, err := os.Lstat(link); err != nil || fi.Mode()&os.ModeSymlink == 0 {
		t.Fatalf("symlink was replaced instead of its target: %v %v", fi, err)
	}
}

